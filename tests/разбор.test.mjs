// Тесты разбора распознанного текста заявки.
//
// Образцы — то, что Drive OCR возвращает с бланка заказчика: таблица
// распознаётся построчно, и значение оказывается то в строке с подписью,
// то в следующей. Оба варианта здесь и проверяются.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { loadGas } from '../tools/load-gas.mjs';

const gas = loadGas(['src/Разбор.js']);
const parse = gas.fn('razborParse_');

const ОТВЕТСТВЕННЫЕ = ['Иванова А.А.', 'Петрова Б.Б.'];
const ПРЕФИКС = 'SC';

// Бланк из жизни: значение стоит в той же строке, что подпись.
const БЛАНК = `
Заказчик - ООО «Заказчик»
Город N
ФИО: Иванова А.А.
Телефон: 89990000000
Заявитель Адрес: ул. Примерная, д. 1
Электронный адрес: ivanova@example.com
Серийный номер SCA10100510L122318286
Модель Пример PC
ПОДРОБНОЕ описание неисправности с описанием
процесса диагностики: не включается
Серийный номер Блока питания (указан внутри на
БП) PC2310001492
Модель диска SSD/NVMe KingSpec 240 GB
Производитель и колличество планок
оперативной памяти KingSpec 1 шт.
`;

test('бланк заказчика разбирается целиком', () => {
  const r = parse(БЛАНК, ОТВЕТСТВЕННЫЕ, ПРЕФИКС);
  assert.equal(r.serial, 'SCA10100510L122318286');
  assert.equal(r.responsible, 'Иванова А.А.');
  assert.equal(r.problem, 'не включается');
});

test('серийник блока питания не подменяет основной', () => {
  const r = parse(БЛАНК, ОТВЕТСТВЕННЫЕ, ПРЕФИКС);
  assert.notEqual(r.serial, 'PC2310001492');
});

test('значение в следующей строке после подписи', () => {
  const текст = `
ФИО:
Петрова Б.Б.
Серийный номер
SB0099123
ПОДРОБНОЕ описание неисправности с описанием
процесса диагностики:
не загружает ОС
Модель диска SSD/NVMe KingSpec 240 GB
`;
  const r = parse(текст, ОТВЕТСТВЕННЫЕ, ПРЕФИКС);
  assert.equal(r.serial, 'SB0099123');
  assert.equal(r.responsible, 'Петрова Б.Б.');
  assert.equal(r.problem, 'не загружает ОС');
});

test('серийники разной длины — признаком служит префикс', () => {
  for (const серийник of ['SC12345', 'SCA10100510L122318286', 'SC-2024-000117']) {
    const r = parse(`Серийный номер ${серийник}\nМодель Пример PC`, ОТВЕТСТВЕННЫЕ, ПРЕФИКС);
    assert.equal(r.serial, серийник, `не распознан ${серийник}`);
  }
});

test('кириллические двойники в серийнике приводятся к латинице', () => {
  // OCR читает «SC» как «ЅС» — глазами не отличить.
  const r = parse('Серийный номер ЅСA10100510С122318286', ОТВЕТСТВЕННЫЕ, ПРЕФИКС);
  assert.equal(r.serial, 'SCA10100510C122318286');
});

test('подпись потеряна — серийник ищется по префиксу во всём тексте', () => {
  const r = parse('Город N\nSCA10100510L122318286\nне включается', ОТВЕТСТВЕННЫЕ, ПРЕФИКС);
  assert.equal(r.serial, 'SCA10100510L122318286');
});

test('ФИО сверяется со справочником, а не пишется как есть', () => {
  // Инициалы OCR путает чаще всего — опознаём по фамилии.
  const r = parse('ФИО: Иванова A.A.', ОТВЕТСТВЕННЫЕ, ПРЕФИКС);
  assert.equal(r.responsible, 'Иванова А.А.', 'должно вернуться каноническое значение из справочника');
});

test('незнакомая фамилия не попадает в таблицу', () => {
  const r = parse('ФИО: Иванов И.И.', ОТВЕТСТВЕННЫЕ, ПРЕФИКС);
  assert.equal(r.responsible, '');
});

test('проблема из нескольких строк собирается и обрывается на следующем поле', () => {
  const текст = `
ПОДРОБНОЕ описание неисправности с описанием
процесса диагностики: не включается,
при нажатии кнопки нет реакции
Серийный номер Блока питания (указан внутри на
БП) PC2310001492
`;
  const r = parse(текст, ОТВЕТСТВЕННЫЕ, ПРЕФИКС);
  assert.equal(r.problem, 'не включается, при нажатии кнопки нет реакции');
});

test('пустой вход не роняет разбор', () => {
  const r = parse('', ОТВЕТСТВЕННЫЕ, ПРЕФИКС);
  assert.deepEqual({ ...r }, { serial: '', responsible: '', problem: '' });
});

/* ───────────────────────────  РУЧНОЙ ВВОД  ──────────────────────────── */

const manual = gas.fn('razborManual_');
const clean = gas.fn('razborCleanSerial_');

test('заявка одной строкой: серийник и проблема', () => {
  const r = manual('SCA10100510L122318286 не включается', ПРЕФИКС);
  assert.equal(r.serial, 'SCA10100510L122318286');
  assert.equal(r.problem, 'не включается');
});

test('заявка двумя строками', () => {
  const r = manual('SC12345\nне загружает ОС, синий экран', ПРЕФИКС);
  assert.equal(r.serial, 'SC12345');
  assert.equal(r.problem, 'не загружает ОС, синий экран');
});

test('один серийник без описания — проблема пустая', () => {
  const r = manual('SC12345', ПРЕФИКС);
  assert.equal(r.serial, 'SC12345');
  assert.equal(r.problem, '');
});

test('текст без серийника не превращается в заявку', () => {
  const r = manual('привет, как дела', ПРЕФИКС);
  assert.equal(r.serial, '');
});

test('серийник, введённый руками, чистится но не отбраковывается', () => {
  // Человек ввёл осознанно: номер чужого формата должен пройти.
  assert.equal(clean(' sc-12 345 '), 'SC-12345');
  assert.equal(clean('ЅСA101С'), 'SCA101C');
  assert.equal(clean('нестандартный7'), 'НЕСТАНДАРТНЫЙ7');
});
